# === Вспомогательные функции для работы с временной БД ===
def setup_test_db(spendings, temp_dir):
    """Создаёт временную users.db с тестовыми тратами для user_id=1"""
    db_path = os.path.join(temp_dir, "users.db")
    
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()
    
    # Создаём таблицы (минимально необходимые)
    cursor.execute('''
        CREATE TABLE IF NOT EXISTS spendings (
            id INTEGER PRIMARY KEY,
            user_id INTEGER,
            description TEXT,
            amount REAL,
            category_main TEXT,
            timestamp TEXT
        )
    ''')
    
    # Вставляем тестовые траты для user_id=1
    for desc, amt, cat, ts in spendings:
        cursor.execute('''
            INSERT INTO spendings (user_id, description, amount, category_main, timestamp)
            VALUES (?, ?, ?, ?, ?)
        ''', (1, desc, amt, cat, ts))
    
    conn.commit()
    conn.close()
    
    return db_path

def run_tests():
    passed = 0
    total = len(test_cases)
    
    for i, case in enumerate(test_cases):
        # Создаём временную папку
        with tempfile.TemporaryDirectory() as temp_dir:
            # Сохраняем оригинальный путь к БД
            original_db = "users.db"
            
            # Создаём тестовую БД
            test_db = setup_test_db(case["spendings"], temp_dir)
            
            # Меняем текущую рабочую директорию или подменяем путь
            # Проще: скопировать в текущую папку, запустить, удалить
            shutil.copy(test_db, original_db)
            
            try:
                # Теперь запускаем агент — он прочитает нашу временную БД
                agent = WeeklyReportAgent()
                report = agent.generate_weekly_report(user_id=1)
                
                # Проверка
                expected_phrases = case["expected_phrases"]
                if all(phrase in report for phrase in expected_phrases):
                    passed += 1
                else:
                    missing = [p for p in expected_phrases if p not in report]
                    print(f"❌ Кейс {i+1}: отсутствуют фразы: {missing}")
                    
            except Exception as e:
                print(f"❌ Кейс {i+1} вызвал ошибку: {e}")
            finally:
                # Удаляем тестовую БД
                if os.path.exists(original_db):
                    os.remove(original_db)
    
    print("\n" + "="*50)
    print(f"Итоги тестирования WeeklyReportAgent:")
    print(f"✅ Пройдено: {passed}/{total} ({passed/total*100:.1f}%)")
    print("="*50)

if __name__ == "__main__":
    run_tests()